export type Libelles = Elargi<typeof brut>;

/** Libellés francisés (typographie française appliquée). */
export const L: Libelles = franciserObjet(brut) as Libelles;

/** Interpolation `{cle}` dans un libellé. */
export function t(libelle: string, params: Record<string, string | number | null | undefined>): string {
  return libelle.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ""));
}

/** Accord en nombre : `pluriel(n, L.contacts.nombreUn, L.contacts.nombre)`. */
export function pluriel(n: number, un: string, plusieurs: string): string {
  return n === 1 ? un : t(plusieurs, { n });
}
